// reproducibility.mjs — the two reviewer-facing reproducibility artifacts
// (#46's "R is deliberately not installed" decision): `out/analysis-data.csv`
// (the exact tidy frame that was fit) and a generated, NEVER-executed
// `out/lme4-fit.R` that lets a reviewer WITH R reproduce the canonical R0
// fit in one command. R is not a build dependency here — these are pointers,
// not infrastructure, per #46's module-shape note. Pure string builders;
// writing the files is the CLI's job (analysis.mjs).

function csvEscape(value) {
  const s = String(value);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/**
 * The exact tidy frame that was fit, as CSV — one row per included cell.
 *
 * @param {ReturnType<typeof import("./frame.mjs").buildFrame>} frame
 * @returns {string}
 */
export function renderAnalysisDataCsv(frame) {
  const header = ["cellKey", "arm", "brief", "replicate", "cfg", frame.responseField, "costUsd"];
  const lines = [header.map(csvEscape).join(",")];
  for (const row of frame.rows) {
    lines.push([row.cellKey, row.armId, row.briefId, row.replicate, row.cfg, row.response, row.costUsd].map(csvEscape).join(","));
  }
  return lines.join("\n") + "\n";
}

/**
 * A generated, never-executed R script reproducing the canonical R0 fit
 * (`lmer(response ~ arm + (1|brief) + (1|brief:arm), data=...)`) against
 * `analysis-data.csv`. Template-generated from the actual formula/level
 * order this run used, not a static disconnected file.
 *
 * @param {{responseField: string, armLevels: string[], referenceArm: string}} spec
 * @returns {string}
 */
export function renderLme4FitR(spec) {
  const { responseField, armLevels, referenceArm } = spec;
  const levelsVec = armLevels.map((a) => `"${a}"`).join(", ");
  return `#!/usr/bin/env Rscript
# lme4-fit.R — generated by evals/analysis/reproducibility.mjs (issue #46).
# NEVER executed by this repo's own tooling — R is deliberately not a build
# dependency (see #46). This script is the reviewer-recognizable canonical
# fit: any reviewer with R can run it against the sibling
# analysis-data.csv to reproduce the same R0 model this run's sidecar fit.
#
#   Rscript out/lme4-fit.R
#
# install.packages("lme4") if not already installed.

library(lme4)

data <- read.csv("analysis-data.csv")
data$arm <- factor(data$arm, levels = c(${levelsVec}))
data$arm <- relevel(data$arm, ref = "${referenceArm}")
data$brief <- factor(data$brief)

fit <- lmer(${responseField} ~ arm + (1 | brief) + (1 | brief:arm), data = data, REML = TRUE)
summary(fit)
confint(fit, method = "Wald")
`;
}
