import { test } from "node:test";
import assert from "node:assert/strict";

import {
  buildJudgeScoreDesignMatrix,
  fitJudgeScoreViaSidecar,
  fitJudgeScoreR1,
  runJudgeScoreLadder,
  SidecarUnavailableError,
} from "./fit.mjs";
import { JUDGE_SCORE_BIAS_COEFFICIENT } from "./judgeScoreFrame.mjs";
import { transpose, multiply, invert } from "./linalg.mjs";

const JUDGE_LEVELS = ["anthropic", "openai"];
const REFERENCE_JUDGE = "anthropic";
const COEF_NAMES = ["Intercept", "judge_provider[T.openai]", JUDGE_SCORE_BIAS_COEFFICIENT];

function toolchain() {
  return { python: "3.11.15", numpy: "2.1.3", scipy: "1.14.1", pandas: "2.2.3", statsmodels: "0.15.0" };
}

function goodVcov(diag = [0.1, 0.15, 0.2]) {
  return diag.map((d, i) => diag.map((_, j) => (i === j ? d : 0)));
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function makeRows() {
  // 6 runs, each with an anthropic + openai leg -- exactly the registered
  // 2-rows-per-pool schedule (Appendix B item 6). Half the runs are
  // anthropic-generated, half openai-generated, so `sameProvider` is NOT
  // perfectly collinear with `judgeProvider` (a design with every pool
  // generated by the same provider would make judge_provider[T.openai] and
  // the bias term linearly dependent -- an always-singular X, never
  // representative of the real schedule where arms vary).
  const rows = [];
  for (let i = 0; i < 6; i++) {
    const run = `pool-${i}`;
    const generatorIsAnthropic = i % 2 === 0;
    // The response genuinely depends on sameProvider (never exactly 0 effect)
    // and includes noise NOT perfectly collinear with any design column
    // ((i % 3) is not proportional to i, judgeProvider, or sameProvider) --
    // a purely `5 + i*0.1`-style deterministic drift with zero true bias
    // effect makes CR2's sandwich degenerate to an exact-zero variance for
    // that column (a fixture artifact, not a production defect).
    const sameProviderAnthropic = generatorIsAnthropic;
    const sameProviderOpenai = !generatorIsAnthropic;
    rows.push({ judgeProvider: "anthropic", sameProvider: sameProviderAnthropic, run, response: 5 + (sameProviderAnthropic ? 0.6 : 0) + (i % 3) * 0.13 });
    rows.push({ judgeProvider: "openai", sameProvider: sameProviderOpenai, run, response: 6 + (sameProviderOpenai ? 0.6 : 0) + ((i + 1) % 3) * 0.11 });
  }
  return rows;
}

// ── buildJudgeScoreDesignMatrix() ───────────────────────────────────────────

test("buildJudgeScoreDesignMatrix: coefficientNames are Intercept, judge_provider[T.<non-ref>], then the bias term", () => {
  const { coefficientNames } = buildJudgeScoreDesignMatrix(makeRows(), JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.deepEqual(coefficientNames, COEF_NAMES);
});

test("buildJudgeScoreDesignMatrix: reference judge_provider row is [1, 0, sameProvider]; non-reference is [1, 1, sameProvider]", () => {
  const rows = [
    { judgeProvider: "anthropic", sameProvider: true, run: "p1" },
    { judgeProvider: "openai", sameProvider: false, run: "p1" },
  ];
  const { X } = buildJudgeScoreDesignMatrix(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.deepEqual(X[0], [1, 0, 1]);
  assert.deepEqual(X[1], [1, 1, 0]);
});

test("buildJudgeScoreDesignMatrix: a row naming a judge_provider outside judgeProviderLevels throws", () => {
  const rows = [{ judgeProvider: "mistral", sameProvider: false, run: "p1" }];
  assert.throws(() => buildJudgeScoreDesignMatrix(rows, JUDGE_LEVELS, REFERENCE_JUDGE), /not in judgeProviderLevels/);
});

test("buildJudgeScoreDesignMatrix: referenceJudgeProvider not in judgeProviderLevels throws", () => {
  assert.throws(() => buildJudgeScoreDesignMatrix(makeRows(), JUDGE_LEVELS, "mistral"), /is not in judgeProviderLevels/);
});

// ── fitJudgeScoreViaSidecar(): rung J0, schema validation + injected runner ─

test("fitJudgeScoreViaSidecar: a well-formed response passes through as rung J0", async () => {
  const runner = async (request) => {
    assert.equal(request.rung, "J0");
    assert.deepEqual(request.coefficientNames, COEF_NAMES);
    assert.equal(request.y.length, request.X.length);
    assert.equal(request.groups.length, request.X.length);
    return {
      converged: true,
      coefficients: [5, 1, 0.5],
      coefficientNames: COEF_NAMES,
      vcov: goodVcov(),
      varianceComponents: { run: 0.3 },
      n: request.y.length,
      toolchain: toolchain(),
    };
  };
  const fit = await fitJudgeScoreViaSidecar(makeRows(), JUDGE_LEVELS, REFERENCE_JUDGE, runner);
  assert.equal(fit.rung, "J0");
  assert.equal(fit.converged, true);
  assert.deepEqual(fit.coefficientNames, COEF_NAMES);
});

test("fitJudgeScoreViaSidecar: coefficientNames mismatch is a hard SidecarUnavailableError, never a positional guess", async () => {
  const runner = async () => ({
    converged: true,
    coefficients: [5, 1, 0.5],
    coefficientNames: ["Intercept", JUDGE_SCORE_BIAS_COEFFICIENT, "judge_provider[T.openai]"], // swapped order
    vcov: goodVcov(),
    varianceComponents: {},
    n: 12,
    toolchain: toolchain(),
  });
  await assert.rejects(() => fitJudgeScoreViaSidecar(makeRows(), JUDGE_LEVELS, REFERENCE_JUDGE, runner), SidecarUnavailableError);
});

test("fitJudgeScoreViaSidecar: runner throwing (missing venv) is a hard failure", async () => {
  const runner = async () => {
    throw new Error("spawn ENOENT");
  };
  await assert.rejects(() => fitJudgeScoreViaSidecar(makeRows(), JUDGE_LEVELS, REFERENCE_JUDGE, runner), SidecarUnavailableError);
});

// ── fitJudgeScoreR1(): pure-Node OLS + CR2 clustered by `run` ───────────────

test("fitJudgeScoreR1: converges and returns a positive-definite vcov with enough runs", () => {
  const fit = fitJudgeScoreR1(makeRows(), JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.equal(fit.rung, "J1");
  assert.equal(fit.converged, true);
  assert.deepEqual(fit.coefficientNames, COEF_NAMES);
  for (let i = 0; i < fit.vcov.length; i++) assert.ok(fit.vcov[i][i] > 0);
});

test("fitJudgeScoreR1: fewer runs (clusters) than parameters -- not converged, named failureReason", () => {
  const rows = [
    { judgeProvider: "anthropic", sameProvider: true, run: "p1", response: 5 },
    { judgeProvider: "openai", sameProvider: false, run: "p1", response: 6 },
  ];
  const fit = fitJudgeScoreR1(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.equal(fit.converged, false);
  assert.match(fit.failureReason, /fewer clusters/);
});

// ── runJudgeScoreLadder(): J0 -> J1 -> J2 ───────────────────────────────────

test("runJudgeScoreLadder: J0 converges cleanly -> stays at J0", async () => {
  const rows = makeRows();
  const runner = async () => ({
    converged: true,
    coefficients: [5, 1, 0.5],
    coefficientNames: COEF_NAMES,
    vcov: goodVcov(),
    varianceComponents: { run: 0.3 },
    n: rows.length,
    toolchain: toolchain(),
  });
  const result = await runJudgeScoreLadder({ rows, judgeProviderLevels: JUDGE_LEVELS, referenceJudgeProvider: REFERENCE_JUDGE, runner });
  assert.equal(result.rung, "J0");
  assert.ok(result.fit);
  assert.deepEqual(result.history.map((h) => h.rung), ["J0"]);
});

test("runJudgeScoreLadder: J0 fails descent (non-convergence) -> falls to J1 (Node CR2)", async () => {
  const rows = makeRows();
  const runner = async () => ({
    converged: false,
    coefficients: [NaN, NaN, NaN],
    coefficientNames: COEF_NAMES,
    vcov: Array.from({ length: 3 }, () => [NaN, NaN, NaN]),
    varianceComponents: {},
    n: rows.length,
    toolchain: toolchain(),
  });
  const result = await runJudgeScoreLadder({ rows, judgeProviderLevels: JUDGE_LEVELS, referenceJudgeProvider: REFERENCE_JUDGE, runner });
  assert.equal(result.rung, "J1");
  assert.ok(result.fit);
  assert.equal(result.fit.converged, true);
  assert.deepEqual(result.history.map((h) => h.rung), ["J0", "J1"]);
});

test("runJudgeScoreLadder: sidecar unavailable is a hard failure, propagated, never silently degraded to J1", async () => {
  const rows = makeRows();
  const runner = async () => {
    throw new Error("spawn ENOENT");
  };
  await assert.rejects(
    () => runJudgeScoreLadder({ rows, judgeProviderLevels: JUDGE_LEVELS, referenceJudgeProvider: REFERENCE_JUDGE, runner }),
    SidecarUnavailableError,
  );
});

// ── (1|run) is load-bearing: clustering by `run` MATERIALLY changes the CI,
//    in a direction that depends on whether the bias term varies WITHIN a
//    pool or is constant within it (textbook Moulton-factor behavior for
//    clustered/repeated-measures data). Both tests below use
//    fitJudgeScoreR1() -- the ACTUAL production fallback rung -- against a
//    naive i.i.d. OLS fit computed with the SAME linalg.mjs primitives over
//    the IDENTICAL design and data -- never a canned/hand-picked pair of
//    numbers, and never a seam the real call site doesn't also exercise.
//
//    IMPORTANT DISCLOSURE (see the PR description for the full derivation):
//    for THIS STUDY'S CURRENT arm mix, `sameProvider` varies WITHIN every
//    pool for 8 of 9 arms (every arm but G) -- both judge legs are always
//    scheduled per pool (matrix.mjs's buildJudgeMatrix), so for a
//    provider-homogeneous arm exactly one leg matches and one doesn't. The
//    registered claim (docs/PREREGISTRATION.md Appendix B item 6, restated in
//    this issue's brief) that omitting (1|run) makes H5's CI "too narrow by
//    roughly the within-pool correlation" does NOT hold for that case --
//    verified below, and independently re-derived in closed form (GLS at the
//    TRUE variance components, no estimation noise) during this issue's
//    investigation. It DOES hold when the bias term is constant within a
//    pool (both legs agree, e.g. arm G's mixed-provider generation, or any
//    future third-provider arm where NEITHER judge leg matches) -- exactly
//    the classic pseudoreplication case the registration describes, and the
//    second test below demonstrates it really is load-bearing THERE. ────────

test("(1|run) narrows the CI for a within-pool-crossed bias term -- the shape every current provider-homogeneous arm (all but G) actually produces", () => {
  const rng = mulberry32(20260901);
  const N_RUNS = 30;
  const BETA = [5, 0.4, 0.6]; // Intercept, judge_provider[T.openai], bias term
  const RUN_SD = 1.4; // strong shared within-pool noise -- the pseudoreplication source
  const EPS_SD = 0.15; // small idiosyncratic per-row noise

  function gaussian() {
    // Box-Muller, driven by the seeded PRNG above -- deterministic across runs.
    const u1 = Math.max(rng(), 1e-9);
    const u2 = rng();
    return Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
  }

  const rows = [];
  for (let i = 0; i < N_RUNS; i++) {
    const run = `pool-${i}`;
    const runEffect = gaussian() * RUN_SD; // shared by BOTH legs of this pool
    // Alternate which provider generated the pool so `sameProvider` is not
    // perfectly collinear with `judgeProvider` (see makeRows()'s comment
    // above for why an always-same-generator design would be singular) --
    // WITHIN every pool, sameProvider still differs between the two legs,
    // matching every provider-homogeneous arm's real schedule.
    const generatorIsAnthropic = i % 2 === 0;
    for (const judgeProvider of JUDGE_LEVELS) {
      const sameProvider = judgeProvider === "anthropic" ? generatorIsAnthropic : !generatorIsAnthropic;
      const mean = BETA[0] + (judgeProvider === "openai" ? BETA[1] : 0) + (sameProvider ? BETA[2] : 0);
      rows.push({ judgeProvider, sameProvider, run, response: mean + runEffect + gaussian() * EPS_SD });
    }
  }

  const clustered = fitJudgeScoreR1(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.equal(clustered.converged, true);

  const { X, coefficientNames } = buildJudgeScoreDesignMatrix(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  const { se: naiveSE } = naiveOlsSE(X, rows.map((r) => r.response), coefficientNames);
  const biasIdx = coefficientNames.indexOf(JUDGE_SCORE_BIAS_COEFFICIENT);
  const clusteredSE = Math.sqrt(clustered.vcov[biasIdx][biasIdx]);

  assert.ok(
    clusteredSE < naiveSE[biasIdx],
    `expected the run-clustered SE (${clusteredSE}) to be SMALLER than naive i.i.d. SE (${naiveSE[biasIdx]}) for a within-pool-crossed bias term -- the run-shared noise cancels in this within-pool contrast, which is the mathematically correct (and verified, see PR description) behavior for this design`,
  );
});

test("(1|run) widens the CI for a between-pool (constant-within-pool) bias term -- the case the registered pseudoreplication concern actually describes", () => {
  const rng = mulberry32(2026);
  const N_RUNS = 60;
  const BETA = [5, 0.4, 0.6];
  const RUN_SD = 1.4;
  const EPS_SD = 0.15;

  function gaussian() {
    const u1 = Math.max(rng(), 1e-9);
    const u2 = rng();
    return Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
  }

  const rows = [];
  for (let i = 0; i < N_RUNS; i++) {
    const run = `pool-${i}`;
    const runEffect = gaussian() * RUN_SD;
    // Half the pools are "mixed-provider" (both legs sameProvider=true, e.g.
    // arm G) and half are a hypothetical third-provider generator (both legs
    // sameProvider=false, since neither judge matches) -- sameProvider is
    // CONSTANT within every pool here, varying only BETWEEN pools. This is
    // the shape a genuinely between-pool covariate takes, and it is the
    // shape the registered pseudoreplication concern (Appendix B item 6)
    // applies to.
    const isMixedProviderPool = i % 2 === 0;
    for (const judgeProvider of JUDGE_LEVELS) {
      const sameProvider = isMixedProviderPool;
      const mean = BETA[0] + (judgeProvider === "openai" ? BETA[1] : 0) + (sameProvider ? BETA[2] : 0);
      rows.push({ judgeProvider, sameProvider, run, response: mean + runEffect + gaussian() * EPS_SD });
    }
  }

  const clustered = fitJudgeScoreR1(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  assert.equal(clustered.converged, true);

  const { X, coefficientNames } = buildJudgeScoreDesignMatrix(rows, JUDGE_LEVELS, REFERENCE_JUDGE);
  const { se: naiveSE } = naiveOlsSE(X, rows.map((r) => r.response), coefficientNames);
  const biasIdx = coefficientNames.indexOf(JUDGE_SCORE_BIAS_COEFFICIENT);
  const clusteredSE = Math.sqrt(clustered.vcov[biasIdx][biasIdx]);

  assert.ok(
    clusteredSE > naiveSE[biasIdx],
    `expected the run-clustered SE (${clusteredSE}) to exceed the naive i.i.d. SE (${naiveSE[biasIdx]}) for a between-pool bias term -- if it doesn't, (1|run)/run-clustering is not doing anything here`,
  );
  assert.ok(clusteredSE / naiveSE[biasIdx] > 1.2, "expected a MEANINGFUL widening, not a rounding-noise difference");
});

/** Classical i.i.d. (homoskedastic) OLS standard errors over `X`/`y`, computed
 *  with fit.mjs's own linalg.mjs primitives -- the "omit (1|run) entirely"
 *  baseline both tests above compare fitJudgeScoreR1's run-clustered SEs
 *  against. Returns `se`, one entry per coefficientNames index. */
function naiveOlsSE(X, y, coefficientNames) {
  const n = X.length;
  const k = coefficientNames.length;
  const Xt = transpose(X);
  const XtXinv = invert(multiply(Xt, X));
  const betaCol = multiply(XtXinv, multiply(Xt, y.map((v) => [v])));
  const fitted = multiply(X, betaCol).map((row) => row[0]);
  const residuals = y.map((v, i) => v - fitted[i]);
  const rss = residuals.reduce((s, e) => s + e * e, 0);
  const sigma2 = rss / (n - k);
  const naiveVcov = XtXinv.map((row) => row.map((v) => v * sigma2));
  return { se: naiveVcov.map((row, i) => Math.sqrt(row[i])), vcov: naiveVcov };
}
